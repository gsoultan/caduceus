// Command saslprep writes wire/saslprep_tables.go, the tables SASLprep needs:
// RFC 3454's, which stringprep's own Unicode 3.2 fixes, read from
// github.com/xdg-go/stringprep, and the Unicode normalization data NFKC needs,
// read from golang.org/x/text/unicode/norm. caduceus requires neither: this
// is a module of its own, run by hand, and the file it writes is checked in.
//
//	cd tools/saslprep && go run . > ../../wire/saslprep_tables.go
//
// It also writes the vectors the normalization is tested against:
//
//	go run . -vectors > ../../wire/testdata/nfkc_vectors.txt
package main

import (
	"bufio"
	"flag"
	"fmt"
	"math/rand/v2"
	"os"
	"slices"
	"strings"
	"unicode/utf8"

	"github.com/xdg-go/stringprep"
	"golang.org/x/text/unicode/norm"
)

func main() {
	vectors := flag.Bool("vectors", false, "write NFKC test vectors instead of the tables")
	flag.Parse()
	out := bufio.NewWriter(os.Stdout)
	defer out.Flush()
	if *vectors {
		writeVectors(out)
		return
	}
	writeTables(out)
}

const (
	hangulFirst = 0xAC00
	hangulLast  = 0xD7A3
)

func scalar(r rune) bool {
	return r < 0xD800 || (r > 0xDFFF && r <= utf8.MaxRune)
}

func writeTables(out *bufio.Writer) {
	fmt.Fprintf(out, "// Copyright (c) 2026 Gembit Soultan Shirazi <gembit.soultan@gmail.com>. All rights reserved.\n\n// Code generated by tools/saslprep; DO NOT EDIT.\n\n")
	fmt.Fprintf(out, "// Tables of RFC 3454 (stringprep), as RFC 4013 (SASLprep) uses them, and\n")
	fmt.Fprintf(out, "// Unicode %s normalization data for NFKC.\n\n", norm.Version)
	fmt.Fprintf(out, "package wire\n\n")

	ranges(out, "saslprepSpace", "C.1.2: non-ASCII space, mapped to U+0020", stringprep.TableC1_2)
	ranges(out, "saslprepNothing", "B.1: commonly mapped to nothing", mappingKeys(stringprep.TableB1))
	prohibited := slices.Concat(stringprep.TableA1, stringprep.TableC1_2, stringprep.TableC2_1,
		stringprep.TableC2_2, stringprep.TableC3, stringprep.TableC4, stringprep.TableC5,
		stringprep.TableC6, stringprep.TableC7, stringprep.TableC8, stringprep.TableC9)
	ranges(out, "saslprepProhibited", "A.1 (unassigned in Unicode 3.2) and C.1.2 to C.9: prohibited", prohibited)
	ranges(out, "saslprepRandAL", "D.1: characters with bidirectional property R or AL", stringprep.TableD1)
	ranges(out, "saslprepL", "D.2: characters with bidirectional property L", stringprep.TableD2)

	decompositions(out)
	classes(out)
	compositions(out)
}

func mappingKeys(m stringprep.Mapping) stringprep.Set {
	var set stringprep.Set
	for r := range m {
		set = append(set, stringprep.RuneRange{r, r})
	}
	return set
}

// ranges writes a set as sorted, merged ranges.
func ranges(out *bufio.Writer, name, doc string, set stringprep.Set) {
	list := slices.Clone(set)
	slices.SortFunc(list, func(a, b stringprep.RuneRange) int { return int(a[0] - b[0]) })
	var merged []stringprep.RuneRange
	for _, r := range list {
		if n := len(merged); n > 0 && r[0] <= merged[n-1][1]+1 {
			merged[n-1][1] = max(merged[n-1][1], r[1])
			continue
		}
		merged = append(merged, r)
	}
	fmt.Fprintf(out, "// %s is %s.\nvar %s = []runeRange{\n", name, doc, name)
	for i, r := range merged {
		if i%4 == 0 {
			out.WriteString("\t")
		}
		fmt.Fprintf(out, "{0x%04X, 0x%04X},", r[0], r[1])
		if i%4 == 3 || i == len(merged)-1 {
			out.WriteString("\n")
		} else {
			out.WriteString(" ")
		}
	}
	out.WriteString("}\n\n")
}

// decompositions writes each code point's full compatibility decomposition,
// where it is not the code point itself, except Hangul syllables, which are
// decomposed by arithmetic.
func decompositions(out *bufio.Writer) {
	var keys []rune
	var offsets []int
	var data strings.Builder
	for r := rune(0); r <= utf8.MaxRune; r++ {
		if !scalar(r) || (r >= hangulFirst && r <= hangulLast) {
			continue
		}
		s := string(r)
		d := norm.NFKD.String(s)
		if d == s {
			continue
		}
		keys = append(keys, r)
		offsets = append(offsets, data.Len())
		data.WriteString(d)
	}
	offsets = append(offsets, data.Len())
	fmt.Fprintf(out, "// nfkdRunes are the code points whose full compatibility decomposition\n")
	fmt.Fprintf(out, "// differs from themselves, in order; nfkdData[nfkdOffsets[i]:nfkdOffsets[i+1]]\n")
	fmt.Fprintf(out, "// is that of nfkdRunes[i].\nvar nfkdRunes = [...]int32{\n")
	numbers(out, len(keys), func(i int) string { return fmt.Sprintf("0x%04X", keys[i]) })
	fmt.Fprintf(out, "}\n\nvar nfkdOffsets = [...]uint16{\n")
	numbers(out, len(offsets), func(i int) string { return fmt.Sprint(offsets[i]) })
	fmt.Fprintf(out, "}\n\nconst nfkdData = ")
	text := data.String()
	for i := 0; i < len(text); i += 64 {
		if i > 0 {
			out.WriteString(" +\n\t")
		}
		fmt.Fprintf(out, "%q", text[i:min(i+64, len(text))])
	}
	out.WriteString("\n\n")
}

// classes writes the canonical combining class of each code point that has
// one other than zero, as ranges of one class.
func classes(out *bufio.Writer) {
	type span struct {
		lo, hi rune
		class  uint8
	}
	var spans []span
	for r := rune(0); r <= utf8.MaxRune; r++ {
		if !scalar(r) {
			continue
		}
		class := norm.NFD.PropertiesString(string(r)).CCC()
		if class == 0 {
			continue
		}
		if n := len(spans); n > 0 && spans[n-1].hi == r-1 && spans[n-1].class == class {
			spans[n-1].hi = r
			continue
		}
		spans = append(spans, span{r, r, class})
	}
	fmt.Fprintf(out, "// combiningClasses are the code points with a canonical combining class\n")
	fmt.Fprintf(out, "// other than zero, as ranges of one class, in order.\nvar combiningClasses = [...]classRange{\n")
	numbers(out, len(spans), func(i int) string {
		return fmt.Sprintf("{0x%04X, 0x%04X, %d}", spans[i].lo, spans[i].hi, spans[i].class)
	})
	out.WriteString("}\n\n")
}

// compositions writes the pairs canonical composition joins, primary
// composites only: a code point whose canonical decomposition is two code
// points, the first of them composed, and which NFC composes them back into.
// Hangul is composed by arithmetic.
func compositions(out *bufio.Writer) {
	type pair struct {
		key      uint64
		composed rune
	}
	var pairs []pair
	for r := rune(0); r <= utf8.MaxRune; r++ {
		if !scalar(r) || (r >= hangulFirst && r <= hangulLast) {
			continue
		}
		d := []rune(norm.NFD.String(string(r)))
		if len(d) < 2 {
			continue
		}
		first := []rune(norm.NFC.String(string(d[:len(d)-1])))
		if len(first) != 1 {
			continue
		}
		second := d[len(d)-1]
		if norm.NFC.String(string(first[0])+string(second)) != string(r) {
			continue
		}
		pairs = append(pairs, pair{uint64(first[0])<<21 | uint64(second), r})
	}
	slices.SortFunc(pairs, func(a, b pair) int {
		switch {
		case a.key < b.key:
			return -1
		case a.key > b.key:
			return 1
		}
		return 0
	})
	fmt.Fprintf(out, "// compositionKeys are the pairs canonical composition joins, the first code\n")
	fmt.Fprintf(out, "// point shifted left 21 bits above the second, in order; compositionRunes[i]\n")
	fmt.Fprintf(out, "// is what compositionKeys[i] composes into.\nvar compositionKeys = [...]uint64{\n")
	numbers(out, len(pairs), func(i int) string { return fmt.Sprintf("0x%X", pairs[i].key) })
	fmt.Fprintf(out, "}\n\nvar compositionRunes = [...]int32{\n")
	numbers(out, len(pairs), func(i int) string { return fmt.Sprintf("0x%04X", pairs[i].composed) })
	out.WriteString("}\n")
}

func numbers(out *bufio.Writer, n int, item func(int) string) {
	for i := range n {
		if i%8 == 0 {
			out.WriteString("\t")
		}
		out.WriteString(item(i))
		out.WriteString(",")
		if i%8 == 7 || i == n-1 {
			out.WriteString("\n")
		} else {
			out.WriteString(" ")
		}
	}
}

// writeVectors writes lines of input and its NFKC, each a Go-quoted string:
// every code point alone, then random strings over the code points with a
// decomposition or a combining class, where the algorithm can go wrong.
func writeVectors(out *bufio.Writer) {
	var interesting []rune
	for r := rune(0); r <= utf8.MaxRune; r++ {
		if !scalar(r) {
			continue
		}
		s := string(r)
		if norm.NFKD.String(s) != s || norm.NFD.PropertiesString(s).CCC() != 0 || (r >= 0x1100 && r <= 0x11FF) {
			interesting = append(interesting, r)
		}
		if n := norm.NFKC.String(s); n != s {
			fmt.Fprintf(out, "%q %q\n", s, n)
		}
	}
	rng := rand.New(rand.NewPCG(1, 2))
	for range 5000 {
		var b strings.Builder
		for range 1 + rng.IntN(6) {
			if rng.IntN(4) == 0 {
				b.WriteRune(rune('a' + rng.IntN(26)))
				continue
			}
			b.WriteRune(interesting[rng.IntN(len(interesting))])
		}
		s := b.String()
		fmt.Fprintf(out, "%q %q\n", s, norm.NFKC.String(s))
	}
}
